import type { RoutogramNode, RoutogramStyleToken, RoutogramTopology } from "@routogram/types";

type ReportOptions = {
  generatedAt?: string;
  project?: string;
};

export function generateArchitectureMarkdown(
  topology: RoutogramTopology,
  options: ReportOptions = {},
): string {
  const routes = topology.nodes
    .filter((node) => node.kind === "route")
    .sort((left, right) => (left.route ?? left.name).localeCompare(right.route ?? right.name));
  const components = topology.nodes.filter((node) => node.kind === "component");
  const client = components.filter((node) => isClient(node));
  const server = components.filter((node) => !isClient(node));
  const tokenUsage = tokenCoverage(topology);
  const deadCss = topology.nodes.filter((node) => getMetrics(node)?.unusedClasses.length);
  const blast = topology.nodes.flatMap((node) =>
    (getMetrics(node)?.blastRadiusWarnings ?? []).map((warning) => ({
      node,
      warning,
    })),
  );
  const generatedAt = options.generatedAt ?? topology.generatedAt;
  const lines = [
    "# Architecture Digest",
    "",
    `> Generated by Routogram at ${generatedAt}.`,
    `> Project: **${options.project ?? "workspace"}** · Schema: v${topology.schemaVersion}`,
    "",
    "## Overview",
    "",
    `- **${topology.nodes.length}** nodes across **${countBy(topology.nodes, "layer")}** layers`,
    `- **${routes.length}** routes, **${components.length}** components`,
    `- **${client.length}** client components, **${server.length}** server/universal components`,
    `- **${(topology.tokens ?? []).length}** design tokens, **${tokenUsage.consumed.size}** consumed`,
    `- **${deadCss.length}** components with dead CSS`,
    `- **${blast.length}** blast-radius warnings`,
    "",
    "## Routing map",
    "",
    "```mermaid",
    "graph TD",
    ...mermaidRoutes(routes),
    "```",
    "",
    ...routeDetails(routes),
    "## Client / Server boundaries",
    "",
    `### Client components (${client.length})`,
    "",
    ...nodeTable(client, "No client components detected."),
    "",
    `### Server / universal components (${server.length})`,
    "",
    ...nodeTable(server, "No server/universal components detected."),
    "",
    "## Design token coverage",
    "",
    `- Defined tokens: **${(topology.tokens ?? []).length}**`,
    `- Consumed tokens: **${tokenUsage.consumed.size}**`,
    `- Unused tokens: **${tokenUsage.unused.length}**`,
    "",
    "| Token | Scope | Value | Consumers |",
    "| --- | --- | --- | ---: |",
    ...tokenUsage.tokens.map(
      (token) =>
        `| \`${token.name}\` | ${token.scope} | \`${token.value}\` | ${tokenUsage.consumers.get(token.name) ?? 0} |`,
    ),
    "",
    "## Dead CSS",
    "",
    deadCss.length === 0
      ? "_No dead CSS detected._"
      : [
          "| Component | File | Unused classes |",
          "| --- | --- | --- |",
          ...deadCss.map((node) => {
            const classes = getMetrics(node)?.unusedClasses ?? [];
            return `| ${node.name} | \`${node.file}\` | ${classes.map((name) => `\`.${name}\``).join(", ")} |`;
          }),
        ].join("\n"),
    "",
    "## Blast radius warnings",
    "",
    blast.length === 0
      ? "_No blast-radius warnings._"
      : [
          "| Component | Selector | Raison | Specificity |",
          "| --- | --- | --- | ---: |",
          ...blast.map(
            ({ node, warning }) =>
              `| ${node.name} | \`${warning.selector}\` | ${warning.reason} | ${warning.specificityScore} |`,
          ),
        ].join("\n"),
    "",
    "## Architecture rulebook",
    "",
    "Run the headless gate before merging:",
    "",
    "```bash",
    "routogram test-arch --format markdown",
    "```",
    "",
  ];

  return lines.join("\n");
}

function routeDetails(routes: RoutogramNode[]): string[] {
  if (routes.length === 0) {
    return ["_No routes detected._", ""];
  }

  const lines = ["### Route tree", "", "```text"];
  for (const route of routes) {
    const depth = Math.max((route.route ?? route.name).split("/").filter(Boolean).length - 1, 0);
    lines.push(`${"  ".repeat(depth)}${route.route ?? route.name}  (${route.file})`);
  }
  lines.push("```", "");

  return lines;
}

function mermaidRoutes(routes: RoutogramNode[]): string[] {
  if (routes.length === 0) {
    return ['  empty["No routes"]'];
  }
  const lines = ['  root["/"]'];
  for (const [index, route] of routes.entries()) {
    const path = route.route ?? route.name;
    if (path === "/") {
      continue;
    }
    lines.push(`  r${index}["${escapeMermaid(path)}"]`);
    lines.push(`  root --> r${index}`);
  }
  return lines;
}

function nodeTable(nodes: RoutogramNode[], empty: string): string[] {
  if (nodes.length === 0) {
    return [empty];
  }
  return [
    "| Component | Route | Runtime | File |",
    "| --- | --- | --- | --- |",
    ...nodes.map(
      (node) =>
        `| ${node.name} | ${node.route ?? "—"} | ${runtimeLabel(node)} | \`${node.file}\` |`,
    ),
  ];
}

function tokenCoverage(topology: RoutogramTopology): {
  tokens: RoutogramStyleToken[];
  consumed: Set<string>;
  unused: RoutogramStyleToken[];
  consumers: Map<string, number>;
} {
  const consumers = new Map<string, number>();
  for (const node of topology.nodes) {
    for (const token of getMetrics(node)?.consumedTokens ?? []) {
      consumers.set(token, (consumers.get(token) ?? 0) + 1);
    }
  }
  const consumed = new Set(consumers.keys());
  const tokens = topology.tokens ?? [];
  return {
    tokens,
    consumed,
    unused: tokens.filter((token) => !consumed.has(token.name)),
    consumers,
  };
}

function getMetrics(node: RoutogramNode) {
  return node.meta?.styleMetrics;
}

function isClient(node: RoutogramNode): boolean {
  return node.runtime === "client" || node.meta?.isServerComponent === false;
}

function runtimeLabel(node: RoutogramNode): string {
  if (isClient(node)) {
    return "client";
  }
  if (node.runtime === "server") {
    return "server";
  }
  return "universal";
}

function countBy(nodes: RoutogramNode[], field: "layer"): string {
  const counts = new Map<string, number>();
  for (const node of nodes) {
    counts.set(node[field], (counts.get(node[field]) ?? 0) + 1);
  }
  return [...counts.entries()].map(([key, value]) => `${key}: ${value}`).join(", ");
}

function escapeMermaid(value: string): string {
  return value.replaceAll('"', "'");
}
